#!/usr/bin/env node
// Propagates the root package.json version to every other version source.
// Run via `pnpm version:sync`; `tools/check-version-sync.mjs` verifies the result in CI.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const { version } = JSON.parse(read('package.json'));

const desktopPath = 'apps/desktop/package.json';
const desktop = JSON.parse(read(desktopPath));
desktop.version = version;
writeFileSync(join(root, desktopPath), JSON.stringify(desktop, null, 2) + '\n');

writeFileSync(
  join(root, 'libs/domain/units/src/lib/version.ts'),
  `// GENERATED by tools/sync-version.mjs from the root package.json — do not edit.\nexport const APP_VERSION = '${version}';\n`,
);

console.log(`version sources synced to ${version}`);
